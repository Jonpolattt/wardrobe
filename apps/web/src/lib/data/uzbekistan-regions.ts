// Tanlangan viloyatning tumanlari. Viloyat tanlanmagan (yoki ro'yxatda
// topilmagan) bo'lsa — bo'sh massiv, ya'ni ikkinchi ro'yxat bo'sh turadi.
export function districtsOf(regionName: string | undefined | null): string[] {
  if (!regionName) return [];
  return UZBEKISTAN_REGIONS.find((r) => r.name === regionName)?.districts ?? [];
}
